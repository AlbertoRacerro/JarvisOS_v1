"""Deterministic serializer from typed Python values to OpenFOAM dictionary syntax.

``dict`` -> sub-dictionary, ``tuple`` -> inline list ``(a b c)``, ``list`` -> one
entry per line, ``int``/``float`` -> number, ``str`` -> token. Tokens and keys are
restricted to a closed character set, so no value can open a directive (``#``),
macro (``$``), comment (``/``), terminate an entry (``;``) or a block (``{}``).
"""

from __future__ import annotations

import math
import re
from typing import Any

BANNER = "// Generated by JarvisOS spec 216 cfd_pipe from a typed study contract. Do not edit."
_TOKEN = re.compile(r'^[A-Za-z0-9_.+\-()|,"*\[\] ]+$')


class FoamDictError(ValueError):
    pass


def _token(value: str) -> str:
    if not _TOKEN.fullmatch(value) or value.count('"') % 2:
        raise FoamDictError(f"unsafe dictionary token: {value!r}")
    return value


def fmt_scalar(value: Any) -> str:
    if isinstance(value, bool):
        raise FoamDictError("bool is ambiguous in OpenFOAM dictionaries; pass a token")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise FoamDictError("non-finite number")
        return format(value, ".12g")
    if isinstance(value, str):
        return _token(value)
    if isinstance(value, tuple):
        return "(" + " ".join(fmt_scalar(item) for item in value) + ")"
    raise FoamDictError(f"unsupported value type {type(value).__name__}")


def _emit(entries: dict[str, Any], indent: int) -> list[str]:
    pad = "    " * indent
    lines: list[str] = []
    for key, value in entries.items():
        key = _token(key)
        if isinstance(value, dict):
            lines += [f"{pad}{key}", f"{pad}{{", *_emit(value, indent + 1), f"{pad}}}"]
        elif isinstance(value, list):
            lines += [f"{pad}{key}", f"{pad}("]
            for item in value:
                if isinstance(item, dict):
                    lines.extend(_emit(item, indent + 1))
                else:
                    lines.append(f"{pad}    {fmt_scalar(item)}")
            lines.append(f"{pad});")
        else:
            lines.append(f"{pad}{key} {fmt_scalar(value)};")
    return lines


def render(foam_class: str, location: str, obj: str, entries: dict[str, Any]) -> str:
    header = {"version": 2.0, "format": "ascii", "class": foam_class, "location": f'"{location}"', "object": obj}
    return "\n".join([BANNER, "FoamFile", "{", *_emit(header, 1), "}", "", *_emit(entries, 0), ""])
