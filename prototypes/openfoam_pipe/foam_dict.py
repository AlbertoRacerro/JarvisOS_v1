"""Minimal deterministic serializer from Python structures to OpenFOAM dictionary syntax.

Mapping: ``dict`` -> sub-dictionary, ``tuple`` -> inline list ``(a b c)``,
``list`` -> one-entry-per-line list, ``bool`` -> on/off is NOT inferred (pass the
token string you want), ``int``/``float`` -> number, ``str`` -> raw token.
Generated dictionaries are therefore always produced from typed values in
``casegen.py``; there is no free-form text path.
"""

from __future__ import annotations

from typing import Any

HEADER_BANNER = "// Generated by prototypes/openfoam_pipe (JarvisOS #913). Do not edit.\n"


def fmt_scalar(value: Any) -> str:
    if isinstance(value, bool):
        raise TypeError("bool is ambiguous in OpenFOAM dictionaries; pass 'on'/'off' or 'true'/'false'")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        text = format(value, ".12g")
        return text
    if isinstance(value, str):
        return value
    if isinstance(value, tuple):
        return "(" + " ".join(fmt_scalar(v) for v in value) + ")"
    raise TypeError(f"unsupported scalar type {type(value).__name__}")


def _emit(entries: dict[str, Any], indent: int) -> list[str]:
    pad = "    " * indent
    lines: list[str] = []
    for key, value in entries.items():
        if isinstance(value, dict):
            lines.append(f"{pad}{key}")
            lines.append(f"{pad}{{")
            lines.extend(_emit(value, indent + 1))
            lines.append(f"{pad}}}")
        elif isinstance(value, list):
            lines.append(f"{pad}{key}")
            lines.append(f"{pad}(")
            for item in value:
                if isinstance(item, dict):  # named sub-dictionaries, e.g. blockMesh boundary
                    lines.extend(_emit(item, indent + 1))
                else:
                    lines.append(f"{pad}    {fmt_scalar(item)}")
            lines.append(f"{pad});")
        else:
            lines.append(f"{pad}{key} {fmt_scalar(value)};")
    return lines


def render(foam_class: str, location: str, obj: str, entries: dict[str, Any]) -> str:
    header = {
        "version": 2.0,
        "format": "ascii",
        "class": foam_class,
        "location": f'"{location}"',
        "object": obj,
    }
    out = [HEADER_BANNER.rstrip("\n"), "FoamFile", "{"]
    out.extend(_emit(header, 1))
    out.append("}")
    out.append("")
    out.extend(_emit(entries, 0))
    out.append("")
    return "\n".join(out)
