import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(resolve(root, path), "utf8");
const source = read("src/pages/studioState.ts").replace('import type { StudioCase, StudioModel } from "../api/studio";', "");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { canPublishStudioDraft } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const cases = [{ inputs: { length: 10 }, expected_outputs: { pressure_drop: 4 }, tolerance: 1e-6 }];
const model = { source_sha256: "source", contract_sha256: "contract", test_cases: cases, last_test_report: { passed: true, source_sha256: "source", contract_sha256: "contract" } };
assert.equal(canPublishStudioDraft(model, cases, false, true), true);
for (const candidate of [null, { ...model, last_test_report: null }, { ...model, last_test_report: { ...model.last_test_report, source_sha256: "old" } }, { ...model, last_test_report: { ...model.last_test_report, passed: false } }]) assert.equal(canPublishStudioDraft(candidate, cases, false, true), false);
assert.equal(canPublishStudioDraft(model, cases, true, true), false);
assert.equal(canPublishStudioDraft(model, cases, false, false), false);
assert.equal(canPublishStudioDraft(model, [], false, true), false);
assert.equal(canPublishStudioDraft(model, [{ inputs: { length: 12 } }], false, true), false);
const page = read("src/pages/Studio.tsx");
for (const text of ["PythonEditor", "VariableForm", "Run Test", "Derived equations", "DerivedDocumentation", "JARVISOS_STUDIO_USER_CODE_ENABLED=1", "Select for calculation", "Revise", "scientifically unqualified"]) assert.ok(page.includes(text), text);
const routes = read("src/app/routes.ts");
assert.match(routes, /path: "\/design\/studio"/);
assert.match(read("src/App.tsx"), /case "design-studio"/);
const derived = read("src/components/studio/DerivedDocumentation.tsx");
for (const text of ["Not rendered:", "syntax_error", "entry_missing", "MathTree"]) assert.ok(derived.includes(text), text);
assert.match(read("package.json"), /npm run test:188/);
console.log("188 Studio frontend ok");
